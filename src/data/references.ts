const openstax = (id: string, section: string, slug: string): Reference => ({
  id,
  title: `Biology 2e, ${section}`,
  source: 'OpenStax',
  authors: 'Clark MA, Douglas M, Choi J',
  year: 2018,
  url: `https://openstax.org/books/biology-2e/pages/${slug}`,
  kind: 'textbook',
});

const cooper = (id: string, title: string, accession: string): Reference => ({
  id,
  title: `The Cell: A Molecular Approach (2nd ed.), “${title}”`,
  source: 'Sinauer Associates, via NCBI Bookshelf',
  authors: 'Cooper GM',
  year: 2000,
  url: `https://www.ncbi.nlm.nih.gov/books/${accession}/`,
  identifier: accession,
  kind: 'textbook',
});

const ods = (id: string, nutrient: string, slug: string): Reference => ({
  id,
  title: `${nutrient}: Fact Sheet for Health Professionals`,
  source: 'NIH Office of Dietary Supplements',
  url: `https://ods.od.nih.gov/factsheets/${slug}-HealthProfessional/`,
  kind: 'factsheet',
});

const motm = (id: string, molecule: string, n: number): Reference => ({
  id,
  title: `Molecule of the Month: ${molecule}`,
  source: 'RCSB PDB-101',
  authors: 'Goodsell DS',
  url: `https://pdb101.rcsb.org/motm/${n}`,
  kind: 'structure',
});

const pdb = (id: string, code: string, title: string): Reference => ({
  id,
  title,
  source: 'RCSB Protein Data Bank',
  url: `https://www.rcsb.org/structure/${code}`,
  identifier: `PDB ${code}`,
  kind: 'structure',
});

const pubchem = (id: string, name: string, cid: number): Reference => ({
  id,
  title: name,
  source: 'PubChem',
  url: `https://pubchem.ncbi.nlm.nih.gov/compound/${cid}`,
  identifier: `CID ${cid}`,
  kind: 'database',
});

